(() => {
  let initialized = false;
  let last = null;
  let loadedAccess = false;
  let loadingAccess = false;
  let statusSignature = "";
  const form = document.getElementById("tts-settings-form");
  if (!form) return;
  const esc = (value) => String(value ?? "").replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;");
  const notify = (message, kind = "success") => {
    if (typeof showToast === "function") showToast(message, kind);
  };
  async function request(url, body) {
    const response = await fetch(url, {
      method: body ? "POST" : "GET", cache: "no-store",
      headers: { Accept: "application/json", ...(body ? { "Content-Type": "application/json" } : {}) },
      ...(body ? { body: JSON.stringify(body) } : {}),
    });
    const data = await response.json();
    if (!response.ok || !data.ok) throw new Error(data.error || "Could not update TTS.");
    return data;
  }
  function fillSettings(settings) {
    for (const [name, value] of Object.entries(settings)) {
      const field = form.elements.namedItem(name);
      if (!field) continue;
      if (field.type === "checkbox") field.checked = Boolean(value);
      else {
        if (name === "reward_id" && value && ![...field.options].some((option) => option.value === value)) {
          field.add(new Option(`Configured reward (${value})`, value));
        }
        field.value = String(value);
      }
    }
  }
  function messages(rows, history = false) {
    if (!rows.length) return `<div class="empty-state"><span class="empty-symbol"><svg class="icon" aria-hidden="true"><use href="#icon-quote"></use></svg></span><strong>${history ? "A little quiet so far" : "Your chat has the mic"}</strong><p>${history ? "Played and skipped messages appear here." : "Redemptions and tests will appear here when they arrive."}</p></div>`;
    return rows.map((row) => {
      const source = row.source === "bits" ? `${row.bits} Bits` : ({ points: "Channel Points", test: "Test", replay: "Replay" }[row.source] || row.source);
      const buttons = history
        ? `<button class="ghost" type="button" data-tts-action="replay" data-id="${esc(row.id)}">Replay</button>`
        : `${row.status === "pending" ? `<button class="primary" type="button" data-tts-action="approve" data-id="${esc(row.id)}">Approve</button>` : ""}<button class="ghost" type="button" data-tts-action="${row.status === "pending" ? "reject" : "skip"}" data-id="${esc(row.id)}">${row.status === "pending" ? "Reject" : "Skip"}</button>`;
      return `<article class="tts-message ${row.status === "playing" ? "is-playing" : ""}"><div class="tts-message-head"><strong>${esc(row.username)}</strong><span class="module-status">${esc(row.status === "pending" ? "Needs approval" : row.status)}</span></div><p>${esc(row.text)}</p><div class="tts-message-bottom"><span>${esc(source)}${row.error ? ` · ${esc(row.error)}` : ""}</span><div class="actions">${buttons}</div></div></article>`;
    }).join("");
  }
  function render(data) {
    if (!data) {
      document.getElementById("tts-settings-note").textContent = "Update or start the bot service to use TTS.";
      return;
    }
    last = data;
    if (!initialized && data.settings && data.engine?.name !== "Offline") {
      fillSettings(data.settings);
      initialized = true;
    }
    const player = document.getElementById("tts-player-status");
    player.textContent = data.player_connected ? "Audio player connected" : "No audio player connected";
    document.getElementById("tts-player-dot").classList.toggle("is-connected", Boolean(data.player_connected));
    const engine = data.engine || {};
    document.getElementById("tts-engine-status").textContent = engine.available ? `${engine.name} · generated by CowBot` : (engine.error || "Speech engine unavailable");
    const connection = data.connection || {};
    document.getElementById("tts-connection-status").textContent = connection.error || (connection.bits && connection.points ? "Bits & Channel Points connected" : "Streamer not connected");
    const rows = data.queue || [];
    const waitingForPlayer = !data.player_connected && rows.some((row) => row.status === "queued");
    const playbackStatus = document.getElementById("tts-playback-status");
    if (data.paused) playbackStatus.textContent = "Queue paused. Click Resume queue to continue playback.";
    else if (!engine.available) playbackStatus.textContent = engine.error || "The speech engine is unavailable. Start the bot to use TTS.";
    else if (!data.player_connected) playbackStatus.textContent = "Waiting for an audio player. Open the browser player to hear speech, or connect the OBS source.";
    else if (rows.some((row) => row.status === "playing")) playbackStatus.textContent = "A message is with the player. If it is silent, check the player for an Enable audio prompt.";
    else if (rows.some((row) => row.status === "queued")) playbackStatus.textContent = "Audio player connected. Queued speech will play automatically.";
    else if (rows.some((row) => row.status === "pending")) playbackStatus.textContent = "Audio player connected. Approve a message below to play it.";
    else playbackStatus.textContent = "Audio player ready. Queue a test to hear CowBot.";
    document.getElementById("tts-playback-help").classList.toggle("needs-player", waitingForPlayer);
    document.getElementById("tts-queue-count").textContent = rows.length;
    const badge = document.getElementById("tts-queue-status");
    badge.textContent = data.paused ? "Paused" : (waitingForPlayer ? "Waiting for player" : (data.settings?.enabled ? "Enabled" : "Viewer TTS off"));
    badge.classList.toggle("is-running", !data.paused && !waitingForPlayer && data.settings?.enabled);
    const pause = document.getElementById("tts-pause");
    pause.dataset.ttsAction = data.paused ? "resume" : "pause";
    pause.textContent = data.paused ? "Resume queue" : "Pause queue";
    const signature = JSON.stringify([rows, data.history]);
    if (signature !== statusSignature) {
      // Preserve keyboard focus when the eight-second status refresh is unchanged.
      document.getElementById("tts-queue").innerHTML = messages(rows);
      document.getElementById("tts-history").innerHTML = messages(data.history || [], true);
      statusSignature = signature;
    }
    if (!loadedAccess && !document.getElementById("panel-tts").hidden) loadAccess();
  }
  async function loadAccess() {
    if (loadingAccess) return;
    loadingAccess = true;
    try {
      const data = await request("/tts/access");
      document.getElementById("tts-overlay-url").value = data.url;
      const playerUrl = new URL(data.url, location.origin);
      playerUrl.searchParams.set("view", "browser");
      const openPlayer = document.getElementById("tts-open-player");
      openPlayer.href = playerUrl.href;
      openPlayer.hidden = false;
      document.getElementById("tts-access-error").textContent = "";
      loadedAccess = true;
    } catch (error) {
      document.getElementById("tts-access-error").textContent = error.message;
    } finally { loadingAccess = false; }
  }
  document.addEventListener("cowbot:status", (event) => render(event.detail));
  document.addEventListener("cowbot:tab", (event) => {
    if (event.detail === "tts" && !loadedAccess) loadAccess();
  });
  document.getElementById("tts-refresh-access").addEventListener("click", loadAccess);
  document.getElementById("tts-load-rewards").addEventListener("click", async (event) => {
    const button = event.currentTarget;
    button.disabled = true;
    try {
      const data = await request("/tts/rewards");
      const select = form.elements.namedItem("reward_id");
      const chosen = select.value;
      select.replaceChildren(new Option("Choose a reward…", ""));
      for (const reward of data.rewards) {
        const option = new Option(`${reward.title} · ${reward.cost} points${reward.input_required ? "" : " (text input required)"}`, reward.id);
        option.disabled = !reward.input_required;
        select.add(option);
      }
      if (chosen && ![...select.options].some((option) => option.value === chosen)) select.add(new Option(`Configured reward (${chosen})`, chosen));
      select.value = chosen;
      document.getElementById("tts-rewards-error").textContent = data.rewards.length ? "" : "No custom rewards found. Create one in your Twitch dashboard first.";
    } catch (error) {
      document.getElementById("tts-rewards-error").textContent = error.message;
    } finally { button.disabled = false; }
  });
  form.addEventListener("submit", async (event) => {
    event.preventDefault();
    const button = form.querySelector('button[type="submit"]');
    if (button.disabled) return;
    button.disabled = true;
    try {
      const settings = Object.fromEntries(new FormData(form));
      form.querySelectorAll('input[type="checkbox"]').forEach((field) => { settings[field.name] = field.checked; });
      const data = await request("/tts", { action: "settings", settings });
      render(data.tts);
      fillSettings(data.tts.settings);
      document.getElementById("tts-settings-note").textContent = "Saved. New viewer messages use these settings.";
      notify("TTS settings saved.");
    } catch (error) { notify(error.message, "error"); }
    finally { button.disabled = false; }
  });
  document.getElementById("tts-test-form").addEventListener("submit", async (event) => {
    event.preventDefault();
    const target = event.currentTarget;
    const button = target.querySelector('button[type="submit"]');
    if (button.disabled) return;
    button.disabled = true;
    try {
      const data = await request("/tts", { action: "test", text: target.elements.namedItem("text").value });
      render(data.tts);
      notify(last?.player_connected ? "Test added to the speech queue." : "Test queued. Click Open browser player to hear it, or connect OBS.");
    } catch (error) { notify(error.message, "error"); }
    finally { button.disabled = false; }
  });
  document.getElementById("panel-tts").addEventListener("click", async (event) => {
    const button = event.target.closest("[data-tts-action]");
    if (!button || button.disabled) return;
    if (button.dataset.confirm && !window.confirm(button.dataset.confirm)) return;
    button.disabled = true;
    try {
      const data = await request("/tts", { action: button.dataset.ttsAction, id: button.dataset.id });
      render(data.tts);
      notify("Speech queue updated.");
    } catch (error) { notify(error.message, "error"); }
    finally { button.disabled = false; }
  });
})();
